import type { LayerPlan, Kind } from './toolpaths'
import type { Settings } from './settings'

export interface PrintStats {
  layers: number
  /** Seconds. */
  time: number
  /** Filament length, mm. */
  filament: number
  /** Grams. */
  mass: number
  /** Total extrusion path length, mm. */
  extruded: number
  lines: number
}

/** Extrusion length (mm of filament) for a printed line of `length` mm. */
export function extrusion(length: number, layerHeight: number, s: Pick<Settings, 'lineWidth' | 'filamentDiameter' | 'flow'>): number {
  const r = s.filamentDiameter / 2
  return (length * layerHeight * s.lineWidth * (s.flow / 100)) / (Math.PI * r * r)
}

/** Time to move `length` mm at up to `speed` mm/s with constant acceleration `acc` mm/s^2 (trapezoid profile). */
export function moveTime(length: number, speed: number, acc = 1000): number {
  if (length <= 0) return 0
  const ramp = speed / acc
  return length >= speed * ramp ? length / speed + ramp : 2 * Math.sqrt(length / acc)
}

const f = (v: number, d = 3) => String(+v.toFixed(d))

/** Marlin-flavoured G-code (relative extrusion) for the planned layers, plus print statistics. */
export function generateGcode(layers: LayerPlan[], s: Settings): { gcode: string; stats: PrintStats } {
  const out: string[] = []
  const speedOf = (k: Kind, first: boolean) => {
    if (first) return s.firstLayerSpeed
    return k === 'outer' || k === 'skirt' ? s.outerSpeed : k === 'inner' ? s.innerSpeed : s.infillSpeed
  }
  let time = 0
  let filament = 0
  let extruded = 0
  let x = 0, y = 0, z = 0
  let retracted = false
  out.push(
    '; generated by Web Slicer (simplified FDM)',
    `; layer height ${s.layerHeight} first ${s.firstLayerHeight} line width ${s.lineWidth} walls ${s.walls} infill ${s.infill}%`,
    `M140 S${f(s.bedTemp, 0)}`,
    `M104 S${f(s.nozzleTemp, 0)}`,
    `M190 S${f(s.bedTemp, 0)}`,
    `M109 S${f(s.nozzleTemp, 0)}`,
    'G21 ; millimetres',
    'G90 ; absolute positioning',
    'M83 ; relative extrusion',
    'G28 ; home all axes',
    'G92 E0',
  )
  const retract = () => {
    if (s.retraction > 0 && !retracted) {
      out.push(`G1 E${f(-s.retraction, 3)} F${f(s.retractSpeed * 60, 0)}`)
      time += s.retraction / s.retractSpeed
      retracted = true
    }
  }
  const unretract = () => {
    if (retracted) {
      out.push(`G1 E${f(s.retraction, 3)} F${f(s.retractSpeed * 60, 0)}`)
      time += s.retraction / s.retractSpeed
      retracted = false
    }
  }
  const travel = (nx: number, ny: number) => {
    const d = Math.hypot(nx - x, ny - y)
    if (d < 1e-6) return
    if (d > s.retractMinTravel) retract()
    out.push(`G0 X${f(nx)} Y${f(ny)} F${f(s.travelSpeed * 60, 0)}`)
    time += moveTime(d, s.travelSpeed)
    x = nx
    y = ny
  }
  layers.forEach((layer, li) => {
    const first = li === 0
    out.push(`;LAYER:${li}`, `;HEIGHT:${f(layer.height)}`)
    retract()
    out.push(`G0 Z${f(layer.z)} F${f(s.travelSpeed * 60, 0)}`)
    time += Math.abs(layer.z - z) / Math.min(s.travelSpeed, 20) // Z moves are slow on most machines
    z = layer.z
    if (li === s.fanFromLayer - 1 && s.fan > 0) out.push(`M106 S${f((s.fan / 100) * 255, 0)}`)
    let lastKind: Kind | null = null
    for (const p of layer.paths) {
      if (p.kind !== lastKind) {
        out.push(`;TYPE:${p.kind}`)
        lastKind = p.kind
      }
      const sp = speedOf(p.kind, first)
      const pts = p.pts
      travel(pts[0], pts[1])
      unretract()
      const n = pts.length / 2
      const count = p.closed ? n + 1 : n
      for (let i = 1; i < count; i++) {
        const nx = pts[(i % n) * 2]
        const ny = pts[(i % n) * 2 + 1]
        const d = Math.hypot(nx - x, ny - y)
        if (d < 1e-6) continue
        const e = extrusion(d, layer.height, s)
        out.push(`G1 X${f(nx)} Y${f(ny)} E${f(e, 4)} F${f(sp * 60, 0)}`)
        time += moveTime(d, sp)
        filament += e
        extruded += d
        x = nx
        y = ny
      }
    }
  })
  retract()
  out.push(
    'M107 ; fan off',
    'M104 S0',
    'M140 S0',
    'G91',
    `G0 Z10 F${f(s.travelSpeed * 60, 0)}`,
    'G90',
    'G0 X0 Y' + f(s.bedY),
    'M84 ; motors off',
  )
  const area = Math.PI * (s.filamentDiameter / 2) ** 2
  const mass = (filament * area * s.filamentDensity) / 1000
  return { gcode: out.join('\n') + '\n', stats: { layers: layers.length, time, filament, mass, extruded, lines: out.length } }
}
